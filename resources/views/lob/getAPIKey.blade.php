<h3>How to Get your Lob API Key</h3>

<h4>Go to Lob.com and login.</h4>

<p>Hover your cursor over your name in the top right-hand corner.  Click on 'Settings'
in the dropdown that appears.</p>

<img src="/images/lob/getApiKeyStep01.png" >

<h4>Click on API Keys</h4>

<p>Click on API Keys in the pop-up that appears.  Copy your live API Key and paste it
    in the form you see on this page.  Then click 'update'.</p>

<img src="/images/lob/getApiKeyStep02.png" >